import { expect, test } from '@playwright/test';

test('배포 화면에서 게스트 온보딩과 실제 상품 분석을 확인한다', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('button', { name: '구글 계정으로 로그인', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '게스트로 시작하기', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('production-entry.png'), fullPage: true });
  await page.getByRole('button', { name: '구글 계정으로 로그인', exact: true }).click();
  await expect(page.getByRole('button', { name: '동의하고 구글로 계속하기' })).toBeDisabled();
  await page.getByRole('button', { name: '처음 화면으로 돌아가기' }).click();
  await page.getByRole('button', { name: '게스트로 시작하기', exact: true }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: '동의하고 게스트로 시작하기' }).click();
  await page.getByLabel('닉네임', { exact: true }).fill('화면 검증용');
  await page.getByLabel('나이(세)').fill('14');
  await page.getByLabel('키(cm)').fill('165');
  await page.getByLabel('몸무게(kg)').fill('55');
  await page.getByRole('button', { name: '목표 계산하기', exact: true }).click();
  await page.getByRole('button', { name: '오늘 먹은 음식 입력하러 가기' }).click();
  await page.getByRole('textbox', { name: '상품명으로 검색' }).fill('바나나킥');
  await page.getByRole('button', { name: '검색', exact: true }).click();
  await expect(page.locator('.result-row').first()).toBeVisible();
  await page.locator('.result-row').first().click();
  await page.getByRole('button', { name: '이 양으로 담기' }).click();
  await page.getByRole('button', { name: '한 끼 평가로 이동' }).click();
  await expect(page.getByRole('heading', { name: '영양소 한눈에', exact: true })).toBeVisible();
  await expect(page.locator('.energy-numbers strong')).not.toHaveText('미확인');
  await page.screenshot({ path: testInfo.outputPath('production-result.png'), fullPage: true });
  await page.getByRole('button', { name: '식사 저장하기' }).click();
  await expect(page.getByText('식사를 이 브라우저에 저장했어요')).toBeVisible();
  await page.getByRole('button', { name: '오늘 전체 보기' }).click();
  await expect(page.locator('.saved-meal-card')).toHaveCount(1);
  await page.screenshot({ path: testInfo.outputPath('production-daily.png'), fullPage: true });
  await page.getByRole('button', { name: '설정', exact: true }).click();
  await expect(page.getByText('게스트로 이용 중')).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('production-settings.png'), fullPage: true });
  await page.reload();
  await expect(page.getByRole('button', { name: '게스트로 시작하기', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
